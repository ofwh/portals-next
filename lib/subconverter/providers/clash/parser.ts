export const clashEntry = tagged('type', { ...proxyReaders, ...actionReaders });

export function parse(content: string): ClashConfig {
  const config = object(parseYaml(content, { uniqueKeys: true, maxAliasCount: 100 }) as unknown);

  if (!('proxies' in config) && !('Proxy' in config)) {
    throw new Error('Clash configuration requires proxies or Proxy');
  }

  const read = nodeItems(clashEntry, 'clash');

  if ('proxies' in config) {
    return {
      ...camelObject(config),
      proxies: read(field(config, 'proxies')),
      ...('Proxy' in config ? { proxy: read(field(config, 'Proxy')) } : {}),
    };
  }

  return { ...camelObject(config), proxy: read(field(config, 'Proxy')) };
}
